// 嵌入资产编码密钥的**唯一定义**。
//
// 页面规则（探针 / 路由分片 / 选择器）在构建期被逐字节异或后编进二进制，运行时再异或回来。
// 编码端在 `build.rs`、解码端在 `probe.rs` / `xhs.rs` / `facebook.rs`，四处曾各写一份同样的字节。
// 四份副本一致时没人看得出问题；一旦有人只改了其中一份，**编译照过、单测照绿** ——
// 只有真跑页面命令时才会拿到一段乱码（或 UTF-8 解码失败后一句「结果无效」），
// 而那时的现场信息与「页面改版」完全无法区分。
//
// 这里只做常量收敛，**不改变任何解码语义**：同样的密钥、同样的 `byte ^ KEY[i % KEY.len()]`。
//
// `build.rs` 用 `include!` 取用本文件（构建脚本是独立编译单元，`use crate::…` 到不了这里），
// 因此 `build.rs` 必须同时声明 `cargo:rerun-if-changed=src/embedded_asset_key.rs` ——
// 少了那一句，改密钥不会触发重新编码，运行时却已换新密钥去解旧资产。
//
// 注意：本文件被 `include!` 进 `build.rs`，所以只能写 `//` 行注释与 `///` 外层文档，
// MUST NOT 用 `//!` 内层文档 —— 展开位置不在文件开头，编译会直接报 E0753。
//
// 边界要诚实：这层编码**只挡扫读，不构成保密**。密钥与算法都随二进制发出去，
// 拿到安装包即可还原。MUST NOT 因为「规则已加密」就把凭据 / 令牌 / 可访问远端系统的密钥
// 塞进同一条通道。

/// 嵌入资产异或编码密钥。编码端与全部解码端共用这一份。
pub const EMBEDDED_ASSET_KEY: &[u8] = &[
    0x91, 0x2f, 0xc4, 0x6a, 0x5d, 0xe3, 0x18, 0xb7, 0x42, 0x0d, 0xfa,
];
